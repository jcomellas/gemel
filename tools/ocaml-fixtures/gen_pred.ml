(* Golden test vectors for gemel-engine's pred module, produced by Unison's
   own src/pred.ml (built with the stand-ins in stubs/ for Util, Prefs and
   Case, and Unison's unicode.ml).

   Usage: gen_pred <fixtures-dir>
   Writes pred.txt, tab-separated, strings as hex ("-" when empty):
     test <mode> <patterns, joined by ','> <string> <test> <assoc_all, joined by ','>
     compile <clause> ok | compile <clause> error <message> *)

let hex s =
  if s = "" then "-" else
  String.concat ""
    (List.map (fun c -> Printf.sprintf "%02x" (Char.code c))
       (List.of_seq (String.to_seq s)))

let modes =
  [ "sensitive", Case.sensitiveOps;
    "insensitive", Case.insensitiveOps;
    "unicode-sensitive", Case.unicodeSensitiveOps;
    "unicode-insensitive", Case.unicodeInsensitiveOps ]

let pred = Pred.create "test" ~category:(`Basic `Sync) ""

(* Pattern lists (newest first, as the preference keeps them) and the
   strings to test against them, in every mode. *)
let cases =
  [ [ "Name *.o"; "Path a/b"; "BelowPath c"; "Regex x[0-9]+";
      "Name {foo,bar}"; "Path src/*.c"; "Name .*"; "BelowPath  d/e  " ],
    [ "foo.o"; "d/foo.o"; "a/b"; "a/b/c"; "c"; "c/d/e"; "cc"; "x12"; "y/x1";
      "foo"; "dir/bar"; "src/a.c"; "src/sub/a.c"; ".hidden"; "d/.git";
      "d/e"; "d/e/f"; ""; "FOO.O" ];
    [ "Name *.c -> cc"; "Name * -> any"; "Name *.h"; "Name a -> b -> c";
      "Path x ->"; "Regex .*\\.txt -> text  "; "Path y -> " ],
    [ "f.c"; "f.h"; "a -> b"; "x"; "notes.txt"; "y"; "d/F.C" ];
    [ "Name *.TXT"; "Path Dir/Sub"; "Name caf\xc3\xa9 -> cafe";
      "Name \xc3\x85ngstr\xc3\xb6m" ],
    [ "a.txt"; "A.TXT"; "dir/sub"; "Dir/Sub"; "caf\xc3\xa9"; "cafe\xcc\x81";
      "CAF\xc3\x89"; "\xc3\x85ngstr\xc3\xb6m"; "\xc3\xa5ngstr\xc3\xb6m";
      "A\xcc\x8angstro\xcc\x88m" ];
    [], [ "a"; "" ] ]

let clauses =
  [ "-> x"; "Foo bar"; "Path /a"; "BelowPath /a"; "Regex a("; ""; "Name";
    "Name "; "Regex ["; "Name a ->  "; "Name a -> b -> "; "Name -> x";
    "  Name   a  "; "Path a/../b"; "Regex (a|b"; "Regex a**"; "name x";
    "Name [a-"; "BelowPath"; "Path"; "Regex" ]

let () =
  let oc = open_out_bin (Filename.concat Sys.argv.(1) "pred.txt") in
  Printf.fprintf oc
    "# Pred golden vectors, generated by tools/ocaml-fixtures/gen_pred.ml.\n\
     # Unison source: %s. OCaml %s, %d-bit.\n\
     # Regenerate with scripts/gen-ocaml-fixtures.sh; do not edit by hand.\n"
    (Option.value (Sys.getenv_opt "UNISON_COMMIT") ~default:"unknown")
    Sys.ocaml_version Sys.word_size;
  List.iter (fun (patterns, strings) ->
      List.iter (fun (mode, ops) ->
          Case.current := ops;
          Pred.intern pred patterns;
          List.iter (fun s ->
              Printf.fprintf oc "test\t%s\t%s\t%s\t%b\t%s\n" mode
                (String.concat "," (List.map hex patterns)) (hex s)
                (Pred.test pred s)
                (String.concat "," (List.map hex (Pred.assoc_all pred s))))
            strings)
        modes)
    cases;
  Case.current := Case.sensitiveOps;
  List.iter (fun c ->
      match Pred.compile_pattern c with
      | _ -> Printf.fprintf oc "compile\t%s\tok\n" (hex c)
      | exception Prefs.IllegalValue m ->
          Printf.fprintf oc "compile\t%s\terror\t%s\n" (hex c) (hex m))
    clauses;
  close_out oc
