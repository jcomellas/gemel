(* Golden test vectors for gemel-ui-api's uicommon and gemel-base's
   truncate_string, produced by Unison's own code: truncateString from
   src/ubase/util.ml, and quote and the Stats module from src/uicommon.ml,
   which scripts/gen-ocaml-fixtures.sh copies in ahead of this file (with
   uicommon_prelude.ml, unicode.ml and the stand-in for Util).

   Usage: gen_uicommon <fixtures-dir>
   Writes uicommon.txt, tab-separated, strings as hex ("-" when empty) and
   floats as their bits in hex (or "nan"):
     truncate <string> <count> <truncateString>
     quote <string> <quote>
     eta <total> <rate> <Stats.eta ~rate with no progress, or "-">
     stats <scenario> <step> <curRate> <avgRate1> <avgRate2> <eta> *)

let hex s =
  if s = "" then "-" else
  String.concat ""
    (List.map (fun c -> Printf.sprintf "%02x" (Char.code c))
       (List.of_seq (String.to_seq s)))

let bits f =
  if Float.is_nan f then "nan" else Printf.sprintf "%Lx" (Int64.bits_of_float f)

let strings =
  [ ""; "a"; "abc"; "abcd"; "/home/me/docs"; "a-very-long-root-name";
    "caf\xc3\xa9-r\xc3\xa9sum\xc3\xa9-na\xc3\xafve";
    "cafe\xcc\x81"; "caf\xe9"; "\xff\xfe\xfdabcdefghijklmno";
    "\xe2\x82\xac\xe2\x82\xac\xe2\x82\xac\xe2\x82\xac\xe2\x82\xac";
    "\xf0\x9f\x98\x80\xf0\x9f\x98\x80\xf0\x9f\x98\x80\xf0\x9f\x98\x80x";
    "ab\x00cd"; "nonexistent"; "symlink"; "directory" ]

let counts = [ 32; 12; 7; 4; 3; 2; 1; 0 ]

let quotes =
  [ "a"; "*.o"; "a->b"; "x-->y"; "a->->b"; "->"; "-->>"; "{,}"; "\\";
    "-"; ">"; "a b"; "[x]?"; "caf\xc3\xa9"; "a/b/c"; "" ]

let totals = [ 0L; 1L; 59L; 60L; 61L; 119L; 120L; 134L; 135L; 149L; 150L;
               1799L; 1800L; 1801L; 1919L; 1920L; 2639L; 2640L; 2700L;
               3419L; 3420L; 3600L; 3779L; 3780L; 86219L; 86220L; 86400L;
               90000L; 1000000L; 123456789L ]

let rates = [ 1.; 2.5; 0.001; 1e6; -1.; Float.nan ]

(* Progress at times (absolute), with the total to do. *)
let scenarios =
  [ "steady", 10_000_000L,
      List.init 40 (fun i -> (100. +. 0.3 *. float i, Int64.of_int (1 + 100_000 * i)));
    "faster", 50_000_000L,
      List.init 40 (fun i -> (5. +. 0.26 *. float i,
                              Int64.of_int (1 + 1000 * i * i)));
    "stall", 1_000_000L,
      [ (1., 1L); (1.3, 1000L); (1.6, 2000L); (1.9, 2000L); (2.2, 2000L);
        (2.3, 2000L); (2.6, 2000L); (5., 2000L); (9., 500_000L);
        (9.1, 500_000L); (9.4, 999_999L); (9.8, 1_000_000L) ];
    "zero-start", 1000L,
      [ (0., 0L); (1., 0L); (2., 10L); (2.1, 20L); (2.5, 40L); (3., 400L) ];
    "jumps", 1_000_000_000L,
      List.init 30 (fun i ->
          (float i *. 0.5,
           Int64.of_int (if i mod 7 = 3 then 1 + i * 10 else 1 + i * 1_000_000))) ]

let () =
  let oc = open_out_bin (Filename.concat Sys.argv.(1) "uicommon.txt") in
  Printf.fprintf oc
    "# uicommon golden vectors, generated by tools/ocaml-fixtures/gen_uicommon.ml.\n\
     # Unison source: %s. OCaml %s, %d-bit.\n\
     # Regenerate with scripts/gen-ocaml-fixtures.sh; do not edit by hand.\n"
    (Option.value (Sys.getenv_opt "UNISON_COMMIT") ~default:"unknown")
    Sys.ocaml_version Sys.word_size;
  List.iter (fun s ->
      List.iter (fun n ->
          Printf.fprintf oc "truncate\t%s\t%d\t%s\n" (hex s) n
            (hex (truncateString s n))) counts) strings;
  List.iter (fun s ->
      Printf.fprintf oc "quote\t%s\t%s\n" (hex s) (hex (quote s))) quotes;
  List.iter (fun total ->
      List.iter (fun rate ->
          let sta = Stats.init total in
          Printf.fprintf oc "eta\t%Ld\t%s\t%s\n" total (bits rate)
            (Stats.eta sta ~rate "-")) rates) totals;
  List.iter (fun (name, total, steps) ->
      let sta = Stats.init total in
      List.iteri (fun i (t, done_) ->
          Stats.update sta t done_;
          Printf.fprintf oc "stats\t%s\t%d\t%s\t%s\t%s\t%s\n" name i
            (bits (Stats.curRate sta)) (bits (Stats.avgRate1 sta))
            (bits (Stats.avgRate2 sta)) (Stats.eta sta "-")) steps) scenarios;
  close_out oc
