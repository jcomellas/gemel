(* Golden test vectors for gemel-rpc's terminal module, produced by
   Unison's own code: the patterns for OpenSSH's messages (passwordRx,
   passphraseRx, authenticityRx and their matchers) and the parser of
   control sequences (parseCtrlSeq, processEscapes) from src/terminal.ml,
   which scripts/gen-ocaml-fixtures.sh copies in ahead of this file (the
   rest of terminal.ml needs Lwt_unix), compiled with rx.ml.

   Usage: gen_terminal <fixtures-dir>
   Writes terminal.txt, tab-separated, strings as hex ("-" when empty):
     escapes <input> <processEscapes>
     ssh <input> <password> <passphrase> <authenticity>
   with the matches as 0 or 1. *)

let hex s =
  if s = "" then "-" else
  String.concat ""
    (List.map (fun c -> Printf.sprintf "%02x" (Char.code c))
       (List.of_seq (String.to_seq s)))

let b x = if x then "1" else "0"

(* What a pseudo-terminal gives: OpenSSH's prompts and messages, Windows
   OpenSSH's escape sequences (see terminal.ml), and every kind of
   sequence the parser knows, cut short and run into each other. *)
let escapes =
  [ ""; "plain text"; "me@server's password: ";
    "\r\n"; "\n"; "\r"; "a\r\nb\n";
    "\027[2J\027[m\027[H\027]0;C:\\WINDOWS\\System32\\OpenSSH\\ssh.exe\007\027[?25h";
    "The authenticity of host 'example.com (127.0.0.1)' can't be established.\r\n\
     ECDSA key fingerprint is SHA256:CxGGHIVL7YDoSAtAzkIJNNaheGW7dDa7m7H+antMzDv.  \r\n\
     Are you sure you want to continue connecting (yes/no/[fingerprint])?\027[10X\027[1C";
    (* CSI: cursor forward, with and without a count, and others. *)
    "a\027[Cb"; "a\027[3Cb"; "a\027[0Cb"; "a\027[12Cb"; "a\027[;Cb";
    "a\027[x3Cb"; "a\027[1;31mred\027[0m"; "a\027[?1049h\027[Hb";
    "a\027[!p"; "a\027[10X"; "a\027[";
    (* Control characters inside sequences, CAN and SUB cancelling them. *)
    "a\027[1\nC"; "a\027[1\024Cb"; "a\027[1\026Cb"; "a\027[1\027[2Cb";
    "a\027[1\127b"; "a\027[1\200b";
    (* OSC, ended by BEL and by ST, and an ESC that isn't ST. *)
    "a\027]0;title\007b"; "a\027]0;title\027\\b"; "a\027]0;t\027[1Cb";
    "a\027]0;t\nx\007b"; "a\027]0;t\024b"; "a\027]unended";
    (* Strings: DCS is not parsed, SOS, PM and APC are. *)
    "a\027Xsos\027\\b"; "a\027^pm\027\\b"; "a\027_apc\027\\b";
    "a\027Pdcs\027\\b"; "a\027X\nx\027\\b"; "a\027Xs\026b"; "a\027Xs\027[2Cb";
    (* Other escapes: intermediates, finals, invalid bytes. *)
    "a\027(Bb"; "a\027( \nBb"; "a\027(\024b"; "a\027(\027[1Cb";
    "a\027=b"; "a\027\027b"; "a\027"; "a\027 \200b";
    (* Bytes from 0x7f up, outside any sequence. *)
    "\127\128\155\200\255"; "caf\195\169";
    (* Every byte, in and out of a sequence. *)
    String.init 256 Char.chr;
    "\027[" ^ String.init 256 Char.chr;
    "\027]" ^ String.init 256 Char.chr;
    "\027X" ^ String.init 256 Char.chr ]

let messages =
  [ ""; "password:"; "Password:"; "me@server's password: ";
    "me@server's password:   "; "me@server's password: x";
    "Password for me@server: "; "assword:"; "password"; "Permission denied, please try again.\r\nme@server's password: ";
    "Enter passphrase for key '/home/me/.ssh/id_ed25519': ";
    "Enter passphrase for key"; "enter passphrase for key '/k': ";
    "The authenticity of host 'saul.cis.upenn.edu (158.130.12.4)' can't be established.\n\
     RSA key fingerprint is d1:d8:5e:08:8c:ae:56:15:66:af:4b:55:53:2a:bc:38.\n\
     Are you sure you want to continue connecting (yes/no)? ";
    "The authenticity of host 'h' can't be established.\r\n\
     Are you sure you want to continue connecting (yes/no/[fingerprint])? ";
    "The authenticity of host 'h' can't be established. continue connecting (yes/no)? ";
    "The authenticity of host 'h' can't be established. continue connecting (yes/no)?";
    "Host key verification failed." ]

let () =
  let oc = open_out_bin (Filename.concat Sys.argv.(1) "terminal.txt") in
  Printf.fprintf oc
    "# terminal golden vectors, generated by tools/ocaml-fixtures/gen_terminal.ml.\n\
     # Unison source: %s. OCaml %s, %d-bit.\n\
     # Regenerate with scripts/gen-ocaml-fixtures.sh; do not edit by hand.\n"
    (Option.value (Sys.getenv_opt "UNISON_COMMIT") ~default:"unknown")
    Sys.ocaml_version Sys.word_size;
  List.iter (fun s ->
      Printf.fprintf oc "escapes\t%s\t%s\n" (hex s) (hex (processEscapes s)))
    escapes;
  List.iter (fun s ->
      Printf.fprintf oc "ssh\t%s\t%s\t%s\t%s\n" (hex s)
        (b (password s)) (b (passphrase s)) (b (authenticity s)))
    messages;
  close_out oc
