let utf16_units = [|
  0x0041; 0x0061; 0x0020; 0x002E; 0x002F; 0x0000; 0x00E9; 0x0301;
  0xF001; 0xF020; 0xF021; 0xF027; 0xF028; 0xF029; 0xF02A; 0xF000;
  0xD800; 0xDBFF; 0xDC00; 0xDFFF; 0xD83D; 0xDE00; 0xFFFF; 0xAC00 |]

let strings oc =
  header oc "Unicode string";
  Printf.fprintf oc
    "# s <in> <normalize> <decompose> <compose> <check_utf_8> <protect> \
     <to_utf_16> <to_utf_16_filename>\n\
     # w <in> <from_utf_16> <from_utf_16_filename>\n\
     # c <a> <b> <compare signs: Sensitive Insensitive UnicodeSensitive \
     UnicodeInsensitive>\n\
     # h <in> <Uutil.hash under each case mode, same order>\n\
     # Byte strings are hex, \"-\" when empty; \"!\" means Unicode.Invalid.\n";
  (* A fixed LCG rather than Random, whose algorithm changed in OCaml 5, so
     that every OCaml version generates the same corpus. *)
  let state = ref 20261019 in
  let random n =
    state := (!state * 1103515245 + 12345) land 0x7FFFFFFF;
    (!state lsr 8) mod n
  in
  let pick a = a.(random (Array.length a)) in
  let random_string () =
    String.concat "" (List.init (random 9) (fun _ -> pick pieces))
  in
  let edge_cases = List.map (fun l -> String.concat "" (List.map utf8 l)) [
      (* Hangul: LV, LVT, syllable + T at and around the T base. *)
      [0x1100; 0x1161]; [0x1100; 0x1161; 0x11A8]; [0x1112; 0x1175; 0x11C2];
      [0xAC00; 0x11A7]; [0xAC00; 0x11A8]; [0xAC01; 0x11A8]; [0xD7A3; 0x11A8];
      [0x1100; 0x11A8]; [0x1113; 0x1161]; [0x1100; 0x1176];
      (* Combining sequences, in and out of canonical order. *)
      [0x61; 0x323; 0x302]; [0x61; 0x302; 0x323]; [0x65; 0x301; 0x301];
      [0x301; 0x61]; [0x3B1; 0x313; 0x301; 0x345]; [0x3B1; 0x345; 0x301];
      [0x55; 0x308; 0x301]; [0x308; 0x301]; [0x304B; 0x3099]; [0x30DB; 0x309A];
      [0x5D9; 0x5B4]; [0x5E9; 0x5BC; 0x5C1]; [0x1D157; 0x1D165];
      [0x41; 0x30A; 0x31B; 0x301]; [0x2126]; [0x212B]; [0x1E9B; 0x323];
      (* SFM characters at and away from the end of a name. *)
      [0x61; 0x20]; [0x61; 0x2E]; [0x61; 0x20; 0x2F; 0x62]; [0x2E; 0x2E];
      [0xF028]; [0xF029; 0x2F]; [0x3F; 0x2A; 0x7C] ] in
  let inputs = edge_cases @ List.init 600 (fun _ -> random_string ()) in
  let fields l = String.concat " " l in
  List.iter (fun s ->
      Printf.fprintf oc "s %s\n" (fields [
          hex s; hex (Unicode.normalize s); hex (Unicode.decompose s);
          hex (Unicode.compose s); bool (Unicode.check_utf_8 s);
          hex (Unicode.protect s);
          hex_or_invalid (catch Unicode.to_utf_16 s);
          hex_or_invalid (catch Unicode.to_utf_16_filename s) ])) inputs;
  let utf16_edge_cases = [
    [0x61; 0xF028]; [0x61; 0xF028; 0x2F]; [0xF029; 0x2F; 0x62]; [0xF028; 0];
    [0xD83D; 0xDE00]; [0xD83D]; [0xDE00; 0xD83D]; [0xD800; 0x41] ] in
  let n = ref 0 in
  for _ = 1 to 300 + List.length utf16_edge_cases do
    let units =
      match List.nth_opt utf16_edge_cases !n with
      | Some l -> incr n; l
      | None -> List.init (random 7) (fun _ -> pick utf16_units)
    in
    let s = String.concat "" (List.map (fun v ->
        String.init 2 (fun i -> Char.chr ((v lsr (8 * i)) land 0xFF))) units) in
    let s = if random 10 = 0 then s ^ "A" else s in
    Printf.fprintf oc "w %s %s %s\n" (hex s)
      (hex_or_invalid (catch Unicode.from_utf_16 s))
      (hex_or_invalid (catch Unicode.from_utf_16_filename s))
  done;
  let pair a b =
    Printf.fprintf oc "c %s %s %s\n" (hex a) (hex b)
      (fields (List.map sign (case_compares a b)))
  in
  let rec pairs = function
    | a :: (b :: _ as rest) ->
        pair a b;
        pair a (String.uppercase_ascii a);
        pair a (Unicode.decompose a);
        pair (Unicode.normalize a) (Unicode.compose a);
        pairs rest
    | _ -> ()
  in
  pairs inputs;
  List.iter (fun s ->
      Printf.fprintf oc "h %s %s\n" (hex s)
        (fields (List.map string_of_int (case_hashes s)))) inputs

let () =
  let fixtures = Sys.argv.(1) and tables_dir = Sys.argv.(2) in
  let with_file dir name f =
    let oc = open_out_bin (Filename.concat dir name) in
    f oc;
    close_out oc
  in
  with_file tables_dir "tables.rs" tables;
  with_file fixtures "unicode_codepoints.txt" codepoints;
  with_file fixtures "unicode_strings.txt" strings
