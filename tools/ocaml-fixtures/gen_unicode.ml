(* Unicode tables and golden test vectors for gemel-compat's `unicode`
   module and gemel-base's `case` module, produced by OCaml Unison's own
   code.

   Linked against Unison's src/unicode.ml and src/unicode_tables.ml, with
   unicode.mli left out so that the tables inside unicode.ml are visible
   (see scripts/gen-ocaml-fixtures.sh).

   Usage: gen_unicode <fixtures-dir> <tables-dir>
   Writes <tables-dir>/tables.rs (the tables, as Rust source) and, in
   <fixtures-dir>:
   - unicode_codepoints.txt: for each block of 0x1000 code points and each
     operation, the MD5 of the outputs for every code point in the block;
   - unicode_strings.txt: inputs and outputs for a pseudo-random corpus.

   Repeats definitions from Unison's src/case.ml and src/ubase/util.ml:
   Derived from Unison, Copyright 1999-2020, Benjamin C. Pierce. *)

let commit () =
  Option.value (Sys.getenv_opt "UNISON_COMMIT") ~default:"unknown"

(* --- Tables as Rust source ---------------------------------------------- *)

let rust_bytes oc name s =
  Printf.fprintf oc "\n#[rustfmt::skip]\npub(super) static %s: &[u8; %d] = b\"\\\n"
    name (String.length s);
  String.iteri (fun i c ->
      if i > 0 && i mod 32 = 0 then output_string oc "\\\n";
      Printf.fprintf oc "\\x%02x" (Char.code c)) s;
  output_string oc "\";\n"

let rust_u32s oc name a =
  Printf.fprintf oc "\n#[rustfmt::skip]\npub(super) static %s: [u32; %d] = [\n"
    name (Array.length a);
  Array.iteri (fun i v ->
      if i mod 8 = 0 then output_string oc "   ";
      Printf.fprintf oc " 0x%08X," v;
      if i mod 8 = 7 || i = Array.length a - 1 then output_string oc "\n") a;
  output_string oc "];\n"

let tables oc =
  Printf.fprintf oc
    "// Unison's Unicode tables, from src/unicode_tables.ml and src/unicode.ml\n\
     // (%s), extracted by tools/ocaml-fixtures/gen_unicode.ml.\n\
     // Regenerate with scripts/gen-ocaml-fixtures.sh; do not edit by hand.\n\
     //\n\
     // Derived from Unison, Copyright 1999-2020, Benjamin C. Pierce.\n"
    (commit ());
  let open Unicode_tables in
  List.iter (fun (name, s) -> rust_bytes oc name s)
    [ "NORM_ASCII", norm_ascii; "NORM_REPL", norm_repl;
      "NORM_PRIM", norm_prim; "NORM_SECOND_HIGH", norm_second_high;
      "NORM_SECOND_LOW", norm_second_low;
      "DECOMP_ASCII", decomp_ascii; "DECOMP_REPL", decomp_repl;
      "DECOMP_PRIM", decomp_prim; "DECOMP_SECOND_HIGH", decomp_second_high;
      "DECOMP_SECOND_LOW", decomp_second_low;
      "COMBINING_PROPERTY_BITMAP", Unicode.combining_property_bitmap;
      "UNI_CHAR_COMBINING_BITMAP", Unicode.uniCharCombiningBitmap;
      "SFM_DECODE", Unicode.sfm_decode ];
  List.iter (fun (name, a) -> rust_u32s oc name a)
    [ "UNI_CHAR_PRECOMP_SOURCE_TABLE", Unicode.uniCharPrecompSourceTable;
      "UNI_CHAR_BMP_PRECOMP_DESTINATION_TABLE",
      Unicode.uniCharBMPPrecompDestinationTable;
      "SFM_ENCODE", Unicode.sfm_encode ]

(* --- Case modes (src/case.ml) ------------------------------------------- *)

external hash_param : int -> int -> 'a -> int = "unsn_hash_univ_param" [@@noalloc]
let hash x = hash_param 10 100 x

let lowercase_latin1 = function
  | 'A' .. 'Z'
  | '\192' .. '\214'
  | '\216' .. '\222' as c ->
    Char.chr(Char.code c + 32)
  | c -> c

let nocase_cmp a b =
  let alen = String.length a in
  let blen = String.length b in
  let minlen = if alen<blen then alen else blen in
  let rec loop i =
    if i>=minlen then compare alen blen
    else
      let c =
        compare (lowercase_latin1(String.get a i)) (lowercase_latin1(String.get b i)) in
      if c<>0 then c else loop (i+1) in
  loop 0

(* compare and hash for Sensitive, Insensitive, UnicodeSensitive and
   UnicodeInsensitive, in that order. *)
let case_compares s s' =
  [ compare (s : string) s'; nocase_cmp s s';
    Unicode.case_sensitive_compare s s';
    Unicode.case_insensitive_compare s s' ]

let case_hashes s =
  [ hash s; hash (String.map lowercase_latin1 s);
    hash (Unicode.decompose s); hash (Unicode.normalize s) ]

(* --- Golden vectors ------------------------------------------------------ *)

let header oc what =
  Printf.fprintf oc
    "# %s golden vectors, generated by tools/ocaml-fixtures/gen_unicode.ml.\n\
     # Unison source: %s. OCaml %s, %d-bit.\n\
     # Regenerate with scripts/gen-ocaml-fixtures.sh; do not edit by hand.\n"
    what (commit ()) Sys.ocaml_version Sys.word_size

let hex s =
  if s = "" then "-" else
  String.concat ""
    (List.map (fun c -> Printf.sprintf "%02x" (Char.code c))
       (List.of_seq (String.to_seq s)))

(* UTF-8 bytes for any value up to 0x10FFFF, surrogates included. *)
let utf8 c =
  let b = Buffer.create 4 in
  let add v = Buffer.add_char b (Char.chr v) in
  if c < 0x80 then add c
  else if c < 0x800 then (add (0xC0 lor (c lsr 6)); add (0x80 lor (c land 0x3F)))
  else if c < 0x10000 then begin
    add (0xE0 lor (c lsr 12));
    add (0x80 lor ((c lsr 6) land 0x3F));
    add (0x80 lor (c land 0x3F))
  end else begin
    add (0xF0 lor (c lsr 18));
    add (0x80 lor ((c lsr 12) land 0x3F));
    add (0x80 lor ((c lsr 6) land 0x3F));
    add (0x80 lor (c land 0x3F))
  end;
  Buffer.contents b

(* UTF-16LE code units for a code point; a surrogate is one unit. *)
let utf16 c =
  let unit v = String.init 2 (fun i -> Char.chr ((v lsr (8 * i)) land 0xFF)) in
  if c < 0x10000 then unit c
  else
    let v = c - 0x10000 in
    unit (0xD800 + v lsr 10) ^ unit (0xDC00 + v land 0x3FF)

(* Unicode.Invalid becomes None so that it can be compared too. *)
let catch f s = try Some (f s) with Unicode.Invalid -> None
let some f s = Some (f s)
let hex_or_invalid = function Some s -> hex s | None -> "!"
let bool b = if b then "1" else "0"
let sign n = string_of_int (compare n 0)

let codepoint_ops = [
  "normalize", (fun c -> some Unicode.normalize (utf8 c));
  "decompose", (fun c -> some Unicode.decompose (utf8 c));
  "compose", (fun c -> some Unicode.compose (utf8 c));
  "compose_decompose",
  (fun c -> some Unicode.compose (Unicode.decompose (utf8 c)));
  "check_utf_8", (fun c -> Some (bool (Unicode.check_utf_8 (utf8 c))));
  "protect", (fun c -> some Unicode.protect (utf8 c));
  "to_utf_16", (fun c -> catch Unicode.to_utf_16 (utf8 c));
  "to_utf_16_filename", (fun c -> catch Unicode.to_utf_16_filename (utf8 c));
  "from_utf_16", (fun c -> catch Unicode.from_utf_16 (utf16 c));
  "from_utf_16_filename", (fun c -> catch Unicode.from_utf_16_filename (utf16 c));
]

(* Each output is length-prefixed ("<len>:<bytes>") before hashing;
   Unicode.Invalid is "!". *)
let codepoints oc =
  header oc "Unicode per-code-point";
  Printf.fprintf oc
    "# <operation> <first code point of block> <MD5 of the block's outputs>\n";
  List.iter (fun (name, f) ->
      for block = 0 to 0x10F do
        let b = Buffer.create 65536 in
        for c = block * 0x1000 to block * 0x1000 + 0xFFF do
          match f c with
          | Some out ->
              Buffer.add_string b (string_of_int (String.length out));
              Buffer.add_char b ':';
              Buffer.add_string b out
          | None -> Buffer.add_char b '!'
        done;
        Printf.fprintf oc "%s %06X %s\n" name (block * 0x1000)
          (Digest.to_hex (Digest.string (Buffer.contents b)))
      done) codepoint_ops

let pieces = Array.concat [
  Array.init 26 (fun i -> String.make 1 (Char.chr (65 + i)));
  Array.init 26 (fun i -> String.make 1 (Char.chr (97 + i)));
  [| "0"; "9"; " "; "."; "/"; "\x00"; "\x7f"; "\""; "*"; ":"; "?"; "|" |];
  (* Raw Latin-1 bytes and broken UTF-8. *)
  [| "\x80"; "\xbf"; "\xc0\xaf"; "\xc1\x81"; "\xc3"; "\xe0\x80\xaf";
