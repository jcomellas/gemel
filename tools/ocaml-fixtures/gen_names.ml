(* Golden test vectors for the regular expressions in Unison's src/name.ml
   and src/path.ml, run through Unison's own Rx engine (src/ubase/rx.ml).

   Usage: gen_names <fixtures-dir>
   Writes names.txt: "<check> <hex input> <0|1>" lines.

   Repeats the regular expressions from Unison's src/name.ml and
   src/path.ml: Derived from Unison, Copyright 1999-2020, Benjamin C. Pierce. *)

(* Name.badWindowsFilenameRx *)
let badWindowsFilenameRx =
  Rx.case_insensitive
    (Rx.rx
       "(.*[\000-\031<>:\"/\\|?*].*)|\
        ((con|prn|aux|nul|com[1-9]|lpt[1-9])(\\..*)?)|\
        (.*[. ])")

(* Path.winAbspathRx and Path.unixAbspathRx *)
let winAbspathRx = Rx.rx "([a-zA-Z]:)?(/|\\\\).*"
let unixAbspathRx = Rx.rx "/.*"

let names = [
  ""; "a"; "abc"; "a b"; " a"; "a "; "a."; "."; ".."; "...";
  "con"; "CON"; "Con"; "cOn.txt"; "con."; "con.."; "conx"; "xcon"; "con x";
  "prn"; "aux"; "nul"; "NUL.tar.gz"; "com0"; "com1"; "COM9"; "com10";
  "com1.x"; "lpt1"; "LPT9.txt"; "lpt0"; "lpt"; "com";
  "a:b"; "a\\b"; "a|b"; "a?b"; "a*b"; "a<b"; "a>b"; "a\"b"; "a/b";
  "\x00"; "a\x00b"; "\x01"; "\x1f"; "\x20"; "\x7f"; "\x80"; "\xff";
  "caf\xc3\xa9"; "c\xd3n"; "c\xf3n"; "\xc3\x89t\xc3\xa9."; "a\nb"; "a\n";
  "c:"; "c:/"; "C:\\x"; "1:/"; "ab:/"; "/"; "/x"; "\\"; "\\x"; "x/";
  "z:\\"; "Z:/foo"; "::/"; "c\\:/" ]

let hex s =
  if s = "" then "-" else
  String.concat ""
    (List.map (fun c -> Printf.sprintf "%02x" (Char.code c))
       (List.of_seq (String.to_seq s)))

let () =
  let oc = open_out_bin (Filename.concat Sys.argv.(1) "names.txt") in
  Printf.fprintf oc
    "# Name/Path regular expression golden vectors, generated by \
     tools/ocaml-fixtures/gen_names.ml.\n\
     # Unison source: %s. OCaml %s, %d-bit.\n\
     # Regenerate with scripts/gen-ocaml-fixtures.sh; do not edit by hand.\n\
     # <check> <input, hex or \"-\"> <1 if it matches>\n"
    (Option.value (Sys.getenv_opt "UNISON_COMMIT") ~default:"unknown")
    Sys.ocaml_version Sys.word_size;
  List.iter (fun s ->
      List.iter (fun (check, rx) ->
          Printf.fprintf oc "%s %s %d\n" check (hex s)
            (if Rx.match_string rx s then 1 else 0))
        [ "bad_file", badWindowsFilenameRx;
          "win_absolute", winAbspathRx;
          "unix_absolute", unixAbspathRx ])
    names;
  close_out oc
