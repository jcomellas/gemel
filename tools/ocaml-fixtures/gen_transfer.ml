(* Golden vectors for gemel-engine's transfer module: the rolling
   checksum, rsync's block sizes, the block information the destination
   sends, and the token stream that the source sends, chunk by chunk, for
   rsync and for plain contents. Built against Unison's own checksum.ml and
   transfer.ml (with Lwt, and stand-ins for Trace and Uutil).

   The files are made by a 64-bit linear congruential generator that the
   Rust tests reproduce: x' = x * 6364136223846793005 + 1442695040888963407,
   each byte being bits 33 to 40 of x'. Each case records the MD5 of its
   inputs, so the tests can check that they made the same ones. *)

let hex s =
  String.concat "" (List.init (String.length s)
    (fun i -> Printf.sprintf "%02x" (Char.code s.[i])))

let md5 s = Digest.to_hex (Digest.string s)

(* [len] bytes from seed [seed]. *)
let random seed len =
  let x = ref (Int64.of_int seed) in
  String.init len (fun _ ->
    x := Int64.add (Int64.mul !x 6364136223846793005L) 1442695040888963407L;
    Char.chr (Int64.to_int (Int64.shift_right_logical !x 33) land 0xff))

let sub s pos len = String.sub s pos len
let drop s n = String.sub s n (String.length s - n)
let take s n = String.sub s 0 n

let with_file name contents f =
  let path = Filename.concat (Filename.get_temp_dir_name ()) name in
  let oc = open_out_bin path in
  output_string oc contents;
  close_out oc;
  let ic = open_in_bin path in
  let r = f ic in
  close_in ic;
  Sys.remove path;
  r

(* A chunk's tokens, summarised: the counts of strings, blocks (and the
   blocks they stand for), and ends. *)
let summary data pos len =
  let s = ref 0 and b = ref 0 and nb = ref 0 and e = ref 0 in
  let rec go p =
    if p < pos + len then
      match data.{p} with
      | 'S' ->
          incr s;
          go (p + 3 + Transfer.decodeInt2 data (p + 1))
      | 'B' ->
          incr b;
          nb := !nb + Transfer.decodeInt1 data (p + 4);
          go (p + 5)
      | 'E' -> incr e; go (p + 1)
      | _ -> failwith "bad token"
  in
  go pos;
  Printf.sprintf "S%d B%d/%d E%d" !s !b !nb !e

let chunks oc =
  fun (data, pos, len) ->
    let bytes = Bytearray.sub data pos len in
    Printf.fprintf oc "chunk\t%d\t%s\t%s\n" len (md5 bytes) (summary data pos len);
    Lwt.return ()

let run t =
  match Lwt.poll t with
  | Some () -> ()
  | None -> failwith "not finished"

(* rsync from [src] (the new file) against [dst] (the old one). *)
let rsync oc name src dst =
  Printf.fprintf oc "case\t%s\t%d\t%s\t%d\t%s\n"
    name (String.length src) (md5 src) (String.length dst) (md5 dst);
  let srcLength = Int64.of_int (String.length src)
  and dstLength = Int64.of_int (String.length dst) in
  let (bi, blockSize) =
    with_file "gen_transfer_dst" dst (fun ic ->
      Transfer.Rsync.rsyncPreprocess ic srcLength dstLength) in
  let info =
    Umarshal.marshal_to_bytearray Transfer.Rsync.mrsync_block_info bi in
  Printf.fprintf oc "info\t%d\t%d\t%d\t%d\t%s\n" blockSize
    bi.Transfer.Rsync.blockCount bi.Transfer.Rsync.checksumSize
    (Bytearray.length info) (md5 (Bytearray.to_string info));
  with_file "gen_transfer_src" src (fun ic ->
    run (Transfer.Rsync.rsyncCompress bi ic srcLength (fun _ -> ())
           (chunks oc)));
  output_string oc "end\n"

(* Plain contents: [declared] bytes said, [contents] in the file. *)
let generic oc name declared contents =
  Printf.fprintf oc "generic\t%s\t%d\t%d\t%s\n"
    name declared (String.length contents) (md5 contents);
  with_file "gen_transfer_src" contents (fun ic ->
    run (Transfer.send ic (Int64.of_int declared) (fun _ -> ()) (chunks oc)));
  output_string oc "end\n"

let () =
  let oc = open_out_bin (Filename.concat Sys.argv.(1) "transfer.txt") in
  Printf.fprintf oc
    "# Transfer golden vectors, generated by tools/ocaml-fixtures/gen_transfer.ml.\n\
     # Unison source: %s. OCaml %s, %d-bit.\n\
     # Regenerate with scripts/gen-ocaml-fixtures.sh; do not edit by hand.\n"
    (Option.value (Sys.getenv_opt "UNISON_COMMIT") ~default:"unknown")
    Sys.ocaml_version Sys.word_size;
  (* The checksum of a string, and rolling it one byte along. *)
  List.iter (fun (seed, len) ->
    let s = random seed (len + 1) in
    let b = Bytes.of_string s in
    let c = Checksum.subbytes b 0 len in
    let rolled = Checksum.roll (Checksum.init len) c s.[0] s.[len] in
    Printf.fprintf oc "checksum\t%s\t%d\t%d\t%d\n"
      (hex s) len c rolled;
    assert (rolled = Checksum.subbytes b 1 len))
    [(1, 1); (2, 2); (3, 7); (4, 64); (5, 700); (6, 1024)];
  (* Block sizes, block counts and strong checksum sizes, around the
     roundings (lengths near 2^(2k+1)). *)
  let lengths =
    [701L; 1000L; 4096L; 65536L; 1048575L; 1048576L; 2097151L; 2097152L;
     2097153L; 8388607L; 8388608L; 8388609L; 33554431L; 33554432L;
     33554433L; 134217727L; 134217728L; 134217729L; 1073741824L;
     68719476736L; 1099511627776L] in
  List.iter (fun dst ->
    List.iter (fun src ->
      let (bs, count, cs) = Transfer.Rsync.sizes src dst in
      Printf.fprintf oc "sizes\t%Ld\t%Ld\t%d\t%d\t%d\n" src dst bs count cs)
      [701L; 1048576L; dst; 1099511627776L])
    lengths;
  let base = random 10 300_000 in
  rsync oc "identical" base base;
  rsync oc "insert-start" (random 11 5000 ^ base) base;
  rsync oc "insert-middle"
    (take base 150_000 ^ random 12 3000 ^ drop base 150_000) base;
  rsync oc "insert-end" (base ^ random 13 2000) base;
  rsync oc "append" (base ^ random 14 80_000) base;
  rsync oc "delete-middle" (take base 100_000 ^ drop base 120_000) base;
  rsync oc "different" (random 15 200_000) base;
  rsync oc "shorter" (take base 50_000) base;
  let zeros n = String.make n '\000' in
  rsync oc "duplicate-blocks"
    (random 16 3000 ^ zeros 100_000 ^ random 17 3000)
    (zeros 64_000 ^ random 18 10_000 ^ zeros 32_000);
  rsync oc "one-byte-each" (sub base 1 299_999) base;
  rsync oc "small" (random 19 1500) (random 19 800);
  rsync oc "big-blocks" (random 20 3_000_000 ^ random 21 500) (random 20 3_000_000);
  List.iter (fun n -> generic oc (Printf.sprintf "plain-%d" n) n (random 30 n))
    [0; 1; 8192; 65497; 65498; 200_000];
  generic oc "plain-short-source" 1000 (random 31 500);
  close_out oc
