(* Golden test vectors for gemel-compat, produced by OCaml Unison's own code.

   Linked against Unison's src/ubase/umarshal.ml, src/bytearray_stubs.c and
   src/hash_compat.c (see scripts/gen-ocaml-fixtures.sh), so the bytes and
   hashes below come from the real implementation running on a real OCaml
   runtime, not from a re-derivation.

   Output: umarshal.txt and ocaml_hash.txt in the directory given as the
   first argument. Each non-comment line is "<case-name> <value>": hex for
   Umarshal encodings (header included), decimal for hashes. The Rust tests
   rebuild each case by name.

   Repeats definitions from Unison's src/uutil.ml and src/props.ml:
   Derived from Unison, Copyright 1999-2020, Benjamin C. Pierce. *)

(* Uutil.hash and Uutil.hash2 (src/uutil.ml). uutil.ml itself pulls in half
   of Unison, so its three definitions are repeated here verbatim. *)
external hash_param : int -> int -> 'a -> int = "unsn_hash_univ_param" [@@noalloc]
let hash x = hash_param 10 100 x
let hash2 x y = (17 * x + 257 * y) land 0x3FFFFFFF

(* Uutil.Filesize.hash *)
let filesize_hash x =
  hash2 (Int64.to_int x) (Int64.to_int (Int64.shift_right_logical x 31))

(* Props.attrvalue and its marshaller (src/props.ml). *)
type attrvalue =
  | String of string
  | Hash of string
  | Loaded of (string * string)

let mattrvalue = Umarshal.(sum3 string string (prod2 string string id id)
                            (function
                             | String v -> I31 v
                             | Hash v -> I32 v
                             | Loaded v -> I33 v)
                            (function
                             | I31 v -> String v
                             | I32 v -> Hash v
                             | I33 v -> Loaded v))
let mattrlist = Umarshal.(list (prod2 string mattrvalue id id))
let msizeandattrs = Umarshal.(prod2 mattrlist int64 id id)
let mxattr = Umarshal.option msizeandattrs

let xattrs =
  Some ([("user.a", String "v");
         ("user.b", Hash "\x01\x02\x03");
         ("com.apple.FinderInfo", Loaded ("full value", "hash"))],
        1234L)

(* A recursive shape for exercising the traversal limits. *)
type nest = L of int | N of nest
let rec nest n = if n = 0 then L 7 else N (nest (n - 1))

let non_utf8 = "\xff\xfe\x00\x80caf\xc3\xa9"
let long_string = String.init 300 (fun i -> Char.chr (i mod 256))

let hex s =
  String.concat ""
    (List.map (fun c -> Printf.sprintf "%02x" (Char.code c))
       (List.of_seq (String.to_seq s)))

let header oc what =
  Printf.fprintf oc
    "# %s golden vectors, generated by tools/ocaml-fixtures/gen_fixtures.ml.\n\
     # Unison source: %s. OCaml %s, %d-bit.\n\
     # Regenerate with scripts/gen-ocaml-fixtures.sh; do not edit by hand.\n"
    what
    (Option.value (Sys.getenv_opt "UNISON_COMMIT") ~default:"unknown")
    Sys.ocaml_version Sys.word_size

let umarshal oc =
  header oc "Umarshal";
  let u name m v =
    Printf.fprintf oc "%s %s\n" name (hex (Umarshal.to_string m v)) in
  let open Umarshal in
  u "unit" unit ();
  u "bool_false" bool false;
  u "bool_true" bool true;
  List.iter (fun (name, i) -> u ("int_" ^ name) int i)
    [ "0", 0; "1", 1; "m1", -1; "127", 127; "128", 128; "m128", -128;
      "m129", -129; "32767", 32767; "32768", 32768; "m32768", -32768;
      "m32769", -32769; "2p30", 1 lsl 30; "2p31m1", (1 lsl 31) - 1;
      "2p31", 1 lsl 31; "m2p31", -(1 lsl 31); "m2p31m1", -(1 lsl 31) - 1;
      "max", max_int; "min", min_int ];
  List.iter (fun (name, i) -> u ("int64_" ^ name) int64 i)
    [ "0", 0L; "2p31", 0x8000_0000L; "max", Int64.max_int;
      "min", Int64.min_int; "m1", -1L ];
  List.iter (fun (name, f) -> u ("float_" ^ name) float f)
    [ "0", 0.0; "m0", -0.0; "1_5", 1.5; "inf", infinity;
      "nan", Int64.float_of_bits 0x7FF8_0000_0000_0001L ];
  u "string_empty" string "";
  u "string_a" string "a";
  u "string_non_utf8" string non_utf8;
  u "string_300" string long_string;
  u "bytearray_hi" bytearray
    (Bigarray.Array1.of_array Bigarray.char Bigarray.c_layout [| 'h'; 'i' |]);
  u "int32bigarray" int32bigarray
    (Bigarray.Array1.of_array Bigarray.int32 Bigarray.c_layout
       [| 0l; 1l; -1l; Int32.max_int; Int32.min_int |]);
  u "option_none" (option int) None;
  u "option_some_int" (option int) (Some 5);
  u "option_some_none" (option (option string)) (Some None);
  u "option_some_some" (option (option string)) (Some (Some "x"));
  u "list_empty" (list int) [];
  u "list_ints" (list int) [1; 2; 300];
  u "list_options" (list (option string)) [Some "a"; None; Some ""];
  u "prod3" (prod3 string int bool id id) ("a", -2, true);
  u "attrvalue_loaded" mattrvalue (Loaded ("full", "h"));
  u "xattr_none" mxattr None;
  u "xattr_empty" mxattr (Some ([], 0L));
  u "xattr_some" mxattr xattrs

let ocaml_hash oc =
  header oc "Legacy OCaml hash (Uutil.hash)";
  let h name v = Printf.fprintf oc "%s %d\n" name (hash v) in
  List.iter (fun (name, i) -> h ("int_" ^ name) i)
    [ "0", 0; "1", 1; "m1", -1; "2p30", 1 lsl 30; "max", max_int;
      "min", min_int ];
  List.iter (fun (name, s) -> h ("string_" ^ name) s)
    [ "empty", ""; "a", "a"; "hello", "hello"; "non_utf8", non_utf8;
      "300", long_string ];
  List.iter (fun (name, i) -> h ("int64_" ^ name) i)
    [ "0", 0L; "m1", -1L; "2p32", 0x1_0000_0000L; "min", Int64.min_int ];
  h "float_1_5" 1.5;
  h "option_none" (None : string option);
  h "option_some" (Some "TEXTMooV");
  h "fullfingerprint" ("0123456789abcdef", "");
  h "xattr_none" (None : ((string * attrvalue) list * int64) option);
  h "xattr_empty" (Some ([], 0L) : ((string * attrvalue) list * int64) option);
  h "xattr_some" xattrs;
  h "tuple_mixed" (1, "a", Some 2L);
  h "list_ints_20" (List.init 20 (fun i -> i));
  h "list_strings_20" (List.init 20 string_of_int);
  h "list_ints_3" [3; 1; 2];
  h "list_strings_4" ["a"; "bc"; ""; "d"];
  h "nest_3" (nest 3);
  h "nest_9" (nest 9);
  h "nest_10" (nest 10);
  h "nest_120" (nest 120);
  let h2 name a b = Printf.fprintf oc "%s %d\n" name (hash2 a b) in
  h2 "hash2_0_0" 0 0;
  h2 "hash2_1_2" 1 2;
  h2 "hash2_m1_max" (-1) max_int;
  h2 "hash2_min_m1" min_int (-1);
  let fs name x = Printf.fprintf oc "%s %d\n" name (filesize_hash x) in
  fs "filesize_0" 0L;
  fs "filesize_1234" 1234L;
  fs "filesize_2p40" 0x100_0000_0000L;
  fs "filesize_max" Int64.max_int

let () =
  let dir = Sys.argv.(1) in
  let with_file name f =
    let oc = open_out_bin (Filename.concat dir name) in
    f oc;
    close_out oc
  in
  with_file "umarshal.txt" umarshal;
  with_file "ocaml_hash.txt" ocaml_hash
