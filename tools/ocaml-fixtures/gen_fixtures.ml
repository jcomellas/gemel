(* The preference dump the client sends the server (src/ubase/prefs.ml):
   mdumpedPrefs, createPrefInternal's dumper for RPC version 1, and
   createBoolWithDefault's marshaller, repeated verbatim. *)
let mdumpedPrefs = Umarshal.(list (prod3 string bool string id id))
let dumper m = let m = Umarshal.(prod2 m (list string) id id) in
  fun value names -> Umarshal.to_string m (value, names)
let mbooldef = Umarshal.(sum3 unit unit unit
                (function
                 | `True -> I31 ()
                 | `False -> I32 ()
                 | `Default -> I33 ())
                (function
                 | I31 () -> `True
                 | I32 () -> `False
                 | I33 () -> `Default))

let prefs_dump oc =
  header oc "Preference dump";
  Printf.fprintf oc
    "# One case: Umarshal.to_string mdumpedPrefs of a dump with one\n\
     # preference of each built-in kind (see crates/gemel-base/tests/).\n";
  let dump = [
    ("batch", false, dumper Umarshal.bool true ["batch"]);
    ("retry", false, dumper Umarshal.int 7 ["retries"; "retry"]);
    ("sshcmd", true, dumper Umarshal.string "ssh -x" ["sshcmd"]);
    ("root", false, dumper Umarshal.(list string) ["b"; "a"] ["root"]);
    ("ignorecase", false, dumper mbooldef `False ["ignorecase"]);
    ("unicode", false, dumper mbooldef `Default ["unicode"]) ] in
  Printf.fprintf oc "dump %s\n" (hex (Umarshal.to_string mdumpedPrefs dump))

(* RPC framing pieces from src/remote.ml, repeated verbatim: intHash and
   encodeInt (over bytes here instead of a Bytearray), and mheader. *)
let intSize = 5

let intHash x = ((x * 791538121) lsr 23 + 17) land 255

let encodeInt m =
  let int_buf = Bytes.create intSize in
  Bytes.set int_buf 0 (Char.chr ( m         land 0xff));
  Bytes.set int_buf 1 (Char.chr ((m lsr 8)  land 0xff));
  Bytes.set int_buf 2 (Char.chr ((m lsr 16) land 0xff));
  Bytes.set int_buf 3 (Char.chr ((m lsr 24) land 0xff));
  Bytes.set int_buf 4 (Char.chr (intHash m));
  Bytes.to_string int_buf

type header =
    NormalResult
  | TransientExn of string
  | FatalExn of string
  | Request of string
  | Stream of string
  | StreamAbort

let mheader = Umarshal.(sum6 unit string string string string unit
                          (function
                           | NormalResult -> I61 ()
                           | TransientExn a -> I62 a
                           | FatalExn a -> I63 a
                           | Request a -> I64 a
                           | Stream a -> I65 a
                           | StreamAbort -> I66 ())
                          (function
                           | I61 () -> NormalResult
                           | I62 a -> TransientExn a
                           | I63 a -> FatalExn a
                           | I64 a -> Request a
                           | I65 a -> Stream a
                           | I66 () -> StreamAbort))

(* canonizeOnServer's argument and result codecs. *)
let mcanonizeArgs = Umarshal.(prod2 (option string) bool id id)
let mcanonizeRes = Umarshal.(prod2 string string id id)

let rpc oc =
  header oc "RPC";
  List.iter (fun n -> Printf.fprintf oc "int %d %s\n" n (hex (encodeInt n)))
    [ 0; 1; 5; 255; 256; 65535; 65536; 1 lsl 24; (1 lsl 31) - 1; 1 lsl 31;
      (1 lsl 32) - 1; 123456789 ];
  let h name v =
    Printf.fprintf oc "header_%s %s\n" name (hex (Umarshal.to_string mheader v)) in
  h "normal" NormalResult;
  h "transient" (TransientExn "oops");
  h "fatal" (FatalExn "bad");
  h "request" (Request "canonizeOnServer");
  h "stream" (Stream "x");
  h "abort" StreamAbort;
  Printf.fprintf oc "canonize_args_some %s\n"
    (hex (Umarshal.to_string mcanonizeArgs (Some "/tmp/x", true)));
  Printf.fprintf oc "canonize_args_none %s\n"
    (hex (Umarshal.to_string mcanonizeArgs (None, true)));
  Printf.fprintf oc "canonize_res %s\n"
    (hex (Umarshal.to_string mcanonizeRes ("host", "/a/b")))

(* ---- Update items (src/common.ml) and the fingerprint cache
   (src/fpcache.ml) ----

   Props.m and the codecs it is made of, copied from props.ml, fileinfo.ml,
   osx.ml, os.ml and fingerprint.ml, with the features as references. Then
   common.ml's codecs, verbatim. *)

let xattrOn = ref false
let aclOn = ref false
let prevState2On = ref false
let xattrEnabled () = !xattrOn
let aclEnabled () = !aclOn

type perm = int * int
let mperm = Umarshal.(prod2 int int id id)

type uid = IdIgnored | IdNamed of string | IdNumeric of int
let mid = Umarshal.(sum3 unit string int
                    (function
                     | IdIgnored -> I31 ()
                     | IdNamed a -> I32 a
                     | IdNumeric a -> I33 a)
                    (function
                     | I31 () -> IdIgnored
                     | I32 a -> IdNamed a
                     | I33 a -> IdNumeric a))

type time = Synced of float | NotSynced of float
let mtime = Umarshal.(sum2 float float
                    (function
                     | Synced a -> I21 a
                     | NotSynced a -> I22 a)
                    (function
                     | I21 a -> Synced a
                     | I22 a -> NotSynced a))

type props = { perm : perm; uid : uid; gid : uid; time : time;
               typeCreator : string option; length : int64; ctime : float;
               xattr : ((string * attrvalue) list * int64) option;
               acl : string option }

let mprops = Umarshal.(prod4
                    (prod6 mperm mid mid mtime (option string) int64 id id)
                    (cond (fun () -> xattrEnabled () || aclEnabled ()) (-1.) float)
                    (cond xattrEnabled None (option msizeandattrs))
                    (cond aclEnabled None (option string))
                    (fun {perm; uid; gid; time; typeCreator; length; ctime; xattr; acl} ->
                       ((perm, uid, gid, time, typeCreator, length), ctime, xattr, acl))
                    (fun ((perm, uid, gid, time, typeCreator, length), ctime, xattr, acl) ->
                       {perm; uid; gid; time; typeCreator; length; ctime; xattr; acl}))

let props_dummy =
  { perm = (0, 0); uid = IdIgnored; gid = IdIgnored; time = NotSynced 0.;
    typeCreator = None; length = -1L; ctime = -1.; xattr = None; acl = None }

type typ = [ `ABSENT | `FILE | `DIRECTORY | `SYMLINK ]
let mtyp = Umarshal.(sum4 unit unit unit unit
                       (function
                        | `ABSENT -> I41 ()
                        | `FILE -> I42 ()
                        | `DIRECTORY -> I43 ()
                        | `SYMLINK -> I44 ())
                       (function
                        | I41 () -> `ABSENT
                        | I42 () -> `FILE
                        | I43 () -> `DIRECTORY
                        | I44 () -> `SYMLINK))

type stamp = InodeStamp of int | NoStamp | RescanStamp
let mstamp = Umarshal.(sum3 int unit unit
                         (function
                          | InodeStamp a -> I31 a
                          | NoStamp -> I32 ()
                          | RescanStamp -> I33 ())
                         (function
                          | I31 a -> InodeStamp a
                          | I32 () -> NoStamp
                          | I33 () -> RescanStamp))

type 'a ressInfo =
    NoRess
  | HfsRess of int64
  | AppleDoubleRess of int * float * float * int64 * 'a
let mressInfo m = Umarshal.(sum3 unit int64
                              (prod5 int float float int64 m id id)
                              (function
                               | NoRess -> I31 ()
                               | HfsRess a -> I32 a
                               | AppleDoubleRess (a, b, c, d, e) -> I33 (a, b, c, d, e))
                              (function
                               | I31 () -> NoRess
                               | I32 a -> HfsRess a
                               | I33 (a, b, c, d, e) -> AppleDoubleRess (a, b, c, d, e)))
let mressStamp = mressInfo Umarshal.unit

let mfullfingerprint = Umarshal.(prod2 string string id id)
let fullfingerprint_dummy = ("", "")

type prevState1 =
    Previous of typ * props * (string * string) * unit ressInfo
  | New1

let mprevState1 = Umarshal.(sum2
                             (prod4 mtyp mprops mfullfingerprint mressStamp id id)
                             unit
                             (function
                              | Previous (a, b, c, d) -> I21 (a, b, c, d)
                              | New1 -> I22 ())
                             (function
                              | I21 (a, b, c, d) -> Previous (a, b, c, d)
                              | I22 () -> New1))

type prevState =
  | PrevDir of props
  | PrevFile of props * (string * string) * stamp * unit ressInfo
  | PrevSymlink
  | New

let mprevState2 = Umarshal.(sum4
                             mprops
                             (prod4 mprops mfullfingerprint mstamp mressStamp id id)
                             unit
                             unit
                             (function
                              | PrevDir a -> I41 a
                              | PrevFile (a, b, c, d) -> I42 (a, b, c, d)
                              | PrevSymlink -> I43 ()
                              | New -> I44 ())
                             (function
                              | I41 a -> PrevDir a
                              | I42 (a, b, c, d) -> PrevFile (a, b, c, d)
                              | I43 () -> PrevSymlink
                              | I44 () -> New))

let prev_to_old = function
  | PrevDir desc ->
      Previous (`DIRECTORY, desc, fullfingerprint_dummy, NoRess)
  | PrevFile (desc, fp, _, ress) ->
      Previous (`FILE, desc, fp, ress)
  | PrevSymlink ->
      Previous (`SYMLINK, props_dummy, fullfingerprint_dummy, NoRess)
  | New ->
      New1

let prev_of_old = function
  | Previous (`DIRECTORY, desc, _, _) -> PrevDir desc
  | Previous (`FILE, desc, fp, ress) -> PrevFile (desc, fp, NoStamp, ress)
  | Previous (`SYMLINK, _, _, _) -> PrevSymlink
  | Previous (`ABSENT, _, _, _)
  | New1 -> New

let newPrevStateType () = !prevState2On

let mprevState = Umarshal.(switch newPrevStateType
  mprevState2 id id
  mprevState1 prev_to_old prev_of_old)

type contentschange =
    ContentsSame
  | ContentsUpdated of (string * string) * stamp * unit ressInfo

let mcontentschange = Umarshal.(sum2 unit (prod3 mfullfingerprint mstamp mressStamp id id)
                                  (function
                                   | ContentsSame -> I21 ()
                                   | ContentsUpdated (a, b, c) -> I22 (a, b, c))
                                  (function
                                   | I21 () -> ContentsSame
                                   | I22 (a, b, c) -> ContentsUpdated (a, b, c)))

type permchange     = PropsSame    | PropsUpdated

let mpermchange = Umarshal.(sum2 unit unit
                              (function
                               | PropsSame -> I21 ()
                               | PropsUpdated -> I22 ())
                              (function
                               | I21 () -> PropsSame
                               | I22 () -> PropsUpdated))

type updateItem =
    NoUpdates
  | Updates of updateContent * prevState
  | Error of string

and updateContent =
    Absent
  | File of props * contentschange
  | Dir of props * (string * updateItem) list * permchange * bool
  | Symlink of string

let mupdateItem_rec mupdateContent =
  Umarshal.(sum3 unit (prod2 mupdateContent mprevState id id) string
              (function
               | NoUpdates -> I31 ()
               | Updates (a, b) -> I32 (a, b)
               | Error a -> I33 a)
              (function
               | I31 () -> NoUpdates
               | I32 (a, b) -> Updates (a, b)
               | I33 a -> Error a))

let mupdateContent_rec mupdateItem =
  Umarshal.(sum4
              unit
              (prod2 mprops mcontentschange id id)
              (prod4 mprops (list (prod2 string mupdateItem id id)) mpermchange bool id id)
              string
              (function
               | Absent -> I41 ()
               | File (a, b) -> I42 (a, b)
               | Dir (a, b, c, d) -> I43 (a, b, c, d)
               | Symlink a -> I44 a)
              (function
               | I41 () -> Absent
               | I42 (a, b) -> File (a, b)
               | I43 (a, b, c, d) -> Dir (a, b, c, d)
               | I44 a -> Symlink a))

let mupdateContent, mupdateItem =
  Umarshal.rec2 mupdateItem_rec mupdateContent_rec

